export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("id");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("numpak-language");
      if (saved === "en" || saved === "id") setLanguageState(saved);
    } catch {
      // Keep Indonesian as the default when browser storage is unavailable.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.title = language === "en"
      ? "Numpak — Make the Most of Trips Going Your Way"
      : "numpak — Manfaatkan Perjalanan Searah";
    try {
      localStorage.setItem("numpak-language", language);
    } catch {
      // The selected language still works for the current page session.
    }
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage: (next) => setLanguageState(next),
    t: (text) => language === "en" ? (en[text] ?? text) : text,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}
